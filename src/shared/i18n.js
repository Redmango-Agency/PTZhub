  let current = 'it';

  function resolve(pref, systemLocale) {
    if (pref && pref !== 'auto' && dictionaries[pref]) return pref;
    const base = String(systemLocale || '').toLowerCase().split(/[-_]/)[0];
    return dictionaries[base] ? base : 'en';
  }

  function setLang(code) {
    if (dictionaries[code]) current = code;
    return current;
  }

  function t(key, vars) {
    const s = (dictionaries[current] && dictionaries[current][key]) ?? dictionaries.it[key] ?? key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  }

  return { t, setLang, resolve, getLang: () => current, LANGUAGES, dictionaries };
