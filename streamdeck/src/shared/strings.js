/** 'it' o 'en' a partire dalle lingue note, in ordine di preferenza. */
export function resolveLang({ ptzLang, sdLang, systemLocale } = {}) {
  if (ptzLang) return String(ptzLang).toLowerCase().startsWith('it') ? 'it' : 'en';
  for (const l of [sdLang, systemLocale]) {
    if (l && String(l).toLowerCase().startsWith('it')) return 'it';
  }
  return 'en';
}

export function translate(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS.en;
  let s = dict[key] ?? STRINGS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}
